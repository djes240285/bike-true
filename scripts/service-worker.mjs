import { createHash } from 'node:crypto';
import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const PRECACHE_EXT = new Set(['.js', '.css', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.woff', '.woff2', '.ico', '.webmanifest']);
const MAX_BYTES = 2_000_000;

export async function writeServiceWorker(distDir) {
  const urls = [];
  await walk(distDir, distDir, urls);
  urls.sort();
  const version = createHash('sha256').update(urls.join('\n')).digest('hex').slice(0, 12);
  await writeFile(path.join(distDir, 'sw.js'), source(version, urls), 'utf8');
}

async function walk(root, dir, urls) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(root, full, urls);
      continue;
    }
    const rel = path.relative(root, full).split(path.sep).join('/');
    if (rel === 'sw.js') continue;
    const ext = path.extname(rel);
    const offline = rel === 'offline/index.html';
    if (!offline && (rel.endsWith('.html') || !PRECACHE_EXT.has(ext))) continue;
    const info = await stat(full);
    if (!offline && info.size > MAX_BYTES) continue;
    urls.push(`/${rel}`);
  }
}

function source(version, urls) {
  return `/* generated by scripts/service-worker.mjs */
const VERSION = ${JSON.stringify(version)};
const URLS = ${JSON.stringify(urls)};
const SHELL = 'biketrue-shell-' + VERSION;
const PAGES = 'biketrue-pages-' + VERSION;
const MEDIA = 'biketrue-mediapipe';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(SHELL).then((cache) =>
      Promise.all(URLS.map((url) => cache.add(url).catch(() => undefined))),
    ),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key !== SHELL && key !== PAGES && key !== MEDIA)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin === self.location.origin) {
    if (url.pathname === '/sw.js') return;
    if (url.pathname.startsWith('/api/') || url.pathname.startsWith('/.netlify/')) return;
    if (url.pathname.endsWith('.mp4') || url.pathname.endsWith('.webm')) return;
    if (request.mode === 'navigate') {
      event.respondWith(networkFirstPage(request));
      return;
    }
    event.respondWith(cacheFirst(request, SHELL));
    return;
  }
  if (url.hostname === 'cdn.jsdelivr.net' || url.hostname === 'storage.googleapis.com') {
    event.respondWith(cacheFirst(request, MEDIA));
  }
});

async function cacheFirst(request, name) {
  const cache = await caches.open(name);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.status === 200 && response.type !== 'opaque') cache.put(request, response.clone());
  return response;
}

async function networkFirstPage(request) {
  const cache = await caches.open(PAGES);
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 4000);
  try {
    const response = await fetch(request, { signal: controller.signal });
    clearTimeout(timer);
    const type = response.headers.get('content-type') || '';
    if (response.status === 200 && !response.redirected && type.includes('text/html')) {
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    clearTimeout(timer);
    const hit = await cache.match(request);
    if (hit) return hit;
    const offline = await caches.match('/offline/index.html');
    if (offline) return offline;
    return new Response('Offline', { status: 503, headers: { 'content-type': 'text/plain; charset=utf-8' } });
  }
}
`;
}
